import http, { download } from './http'

export const login = (data) => http.post('/auth/login/', data)
export const fetchRooms = () => http.get('/rooms/')
export const createRoom = (data) => http.post('/rooms/', data)
export const updateRoom = (id, data) => http.patch(`/rooms/${id}/`, data)
export const replaceSlots = (id, data) => http.put(`/rooms/${id}/slots/`, data)
export const fetchRoom = (id) => http.get(`/rooms/${id}/`)
export const fetchSeatBoard = (id, params) => http.get(`/rooms/${id}/seats/`, { params })
export const batchSeats = (id, data) => http.post(`/rooms/${id}/seats/batch/`, data)
export const updateSeat = (id, data) => http.patch(`/seats/${id}/`, data)
export const fetchReservations = (params) => http.get('/reservations/', { params })
export const adminCancel = (id, reason) => http.post(`/reservations/${id}/admin-cancel/`, { reason })
export const fetchUsers = (params) => http.get('/users/', { params })
export const setUserStatus = (id, isActive) => http.patch(`/users/${id}/status/`, { is_active: isActive })
export const resetPassword = (id) => http.post(`/users/${id}/reset-password/`)
export const fetchOverview = () => http.get('/stats/overview/')
export const fetchSeatStats = (params) => http.get('/stats/seats/', { params })
export const fetchUserStats = (params) => http.get('/stats/users/', { params })
export const fetchUtilization = (params) => http.get('/stats/utilization/', { params })
export const exportSeatStats = (params) => download(`/stats/export/?${new URLSearchParams(params).toString()}`, '座位使用统计.xlsx')
